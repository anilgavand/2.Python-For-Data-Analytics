# Python Arithmatic Operators

# 1. Addition Operator = The addition operator (+) is used to add two numbers together.
# 2. Subtraction Operator = The subtraction operator (-) is used to subtract one number from another.
# 3. Multiplication Operator = The multiplication operator (*) is used to multiply two numbers.
# 4. Division Operator = The division operator (/) is used to divide one number by another.
# 5. Modulus Operator = The modulus operator (%) is used to find the remainder of a division operation.
# 6. Floor Division Operator = The floor division operator (//) is used to find the quotient of a division operation, rounded down to the nearest integer.
# 7. Exponentiation Operator = The exponentiation operator (**) is used to raise a number to a power.


print("----------------------------------------------------------------------------------")
a=int(input("Enter the First Value :"))
b=int(input("Enter the Second Value :"))
print("Addition of two values is :",a+b)
print("Subtraction of two values is :",a-b) 
print("Multiplication of two values is :",a*b)
print("Division of two values is :",a/b)
print("Modulus of two values is :",a%b)
print("Floor Division of two values is :",a//b) 
print("Exponentiation of two values is :",a**b)
