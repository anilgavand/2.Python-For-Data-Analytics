# Assignment Operators

# They are used to assign values to variables.

# 1. Simple Assignment Operator (=) : It is used to assign the value of the right operand to the left operand.
# 2. Addition Assignment Operator (+=) : It is used to add the right operand to the left operand and then assign the result to the left operand.
# 3. Subtraction Assignment Operator (-=) : It is used to subtract the right operand from the left operand and then assign the result to the left operand.
# 4. Multiplication Assignment Operator (*=) : It is used to multiply the right operand with the left operand and then assign the result to the left operand.
# 5. Division Assignment Operator (/=) : It is used to divide the left operand by the right operand and then assign the result to the left operand.
# 6. Modulus Assignment Operator (%=) : It is used to find the remainder of a division operation between the left and right operands and then assign the result to the left operand.
# 7. Floor Division Assignment Operator (//=) : It is used to find the quotient of a division operation between the left and right operands, rounded down to the nearest integer, and then assign the result to the left operand.
# 8. Exponentiation Assignment Operator (**=) : It is used to raise the left operand to the power of the right operand and then assign the result to the left operand.

