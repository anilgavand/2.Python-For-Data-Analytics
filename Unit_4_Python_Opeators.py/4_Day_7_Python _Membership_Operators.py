# Membership Operators

# They are used to test if a sequence is present in an object.

# 1. IN Operator (in) : Returns True if a specified value is present in the object, otherwise returns False.
# 2. NOT IN Operator (not in) : Returns True if a specified value is not present in the object, otherwise returns False.

# Example No: 1

my_list = [1, 2, 3, 4, 5]
print("IN Operator (in) :", 3 in my_list)
print("NOT IN Operator (not in) :", 6 not in my_list)
