# Arguments In Functions

'''
Arguments allow us to give different inputs to the same function,
so the function can perform its task using those inputs.

def greetings(name):                 # Name is parameter
    print("Hello, " + name + "!")

greetings("Anil")                    # Anil as argument

'''
'''
Types of Function Arguments in Python
1. Required Arguments (Positional Arguments)
2. Default Arguments
3. Keyword Arguments (Named Arguments)
4. Arbitrary Arguments (*args)
5. Arbitrary Keyword Arguments (**kwargs)

'''