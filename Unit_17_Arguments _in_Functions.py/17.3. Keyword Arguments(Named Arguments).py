# Keyword Argument

# Exampe .1 Function Define with two Paramater

def devide(a,b):  # Here a and b is two Parameter
    return a/b

result=devide(b=10,a=5)        # with keyword Arguments a=5
print("The result is:",result) 

result=devide(10,5)            # positional Arguments(10,5)
print("The result is :",result)  
